'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {setup,tick}=require('./ballistic.test.cjs');
function asset(name){
 const file=['../dist/','../'].map(dir=>path.join(__dirname,dir+name)).find(f=>fs.existsSync(f));
 assert.ok(file,'bundled '+name);return fs.readFileSync(file);
}
const musicAsset=asset('arena-background-1.mp3'),echoAsset=Buffer.from(asset('ballistic-burst-echo-sfx.js').toString().match(/RIFT_BALLISTIC_BURST_ECHO_MP3_BASE64='([A-Za-z0-9+/=]+)'/)[1],'base64');
assert.ok(musicAsset.length>20000&&musicAsset.length<100000,'bounded game mix download');
const reply=async content=>({ok:true,arrayBuffer:async()=>Uint8Array.from(content).buffer});
const prepare=({saved='ballistic',...p}={})=>setup({saved,musicAsset,musicFetch:()=>reply(musicAsset),echoAsset,...p});
const start=async p=>{const q=prepare(p);q.open('start');await tick();return q;};
const fire=q=>{q.pointer('pointerdown');q.pointer('pointerup');};
const select=q=>q.click('gun-ballistic',{detail:1,pointerType:'touch',pointerId:20});
const nearly=(a,b)=>assert.ok(Math.abs(a-b)<1e-9,a+' ~ '+b);
(async()=>{
 const q=prepare();
 q.click('test-sound');await tick();
 assert.equal(q.musicVoices.length,0);assert.equal(q.musicFetches.length,0,'test/menu does not start or download music');
 q.click('open-hangar');q.click('hangar-canopy-button');q.click('close-hangar');await tick();
 assert.equal(q.musicVoices.length,0,'hangar does not start music');
 q.open('start');await tick();
 assert.deepEqual(q.musicFetches,['./arena-background-1.mp3?v=1']);
 const first=q.musicVoices[0];
 assert.ok(first);assert.equal(first.loop,true);nearly(first.offset,.096);
 nearly(first.loopEnd-first.loopStart,10.56);
 assert.deepEqual(first.level.gain.ramps,[[.10,.4]],'350ms+ quiet fade in');
 q.step(40);fire(q);
 assert.equal(q.musicVoices.length,1);
 nearly(first.level.gain.ramps.at(-2)[0],.036);nearly(first.level.gain.ramps.at(-1)[0],.10);
 const firstRecovery=first.level.gain.ramps.at(-1)[1];
 q.step(4);fire(q);
 assert.ok(first.level.gain.ramps.at(-1)[1]>firstRecovery,'repeated shots extend duck without loop restart');
 q.step(40);select(q);q.step(6);select(q);fire(q);q.step(18);
 assert.equal(q.echoes.length,1,'V32 Ballistic Burst echo still plays beside loop');
 assert.equal(q.inspect().practiceShots,8);assert.equal(q.musicVoices.length,1);
 assert.equal(q.native.length,0,'arena music is never native fallback');
 q.reset();assert.equal(q.musicVoices.length,1,'field reset leaves valid playing music alone');
 q.click('open-hangar');assert.equal(first.disconnected,true,'entering Hangar stops music');
 q.click('close-hangar');assert.equal(q.musicVoices.length,2,'returning to flight resumes music');
 q.key('keydown','KeyP');assert.equal(q.musicVoices.at(-1).disconnected,true);
 q.open('resume');assert.equal(q.musicVoices.length,3);
 q.click('test-phone-audio');assert.equal(q.musicVoices.at(-1).disconnected,true);
 q.native[0].onended();
 assert.equal(q.musicVoices.length,4,'native-only sound diagnostic returns to arena music');
 q.mute();assert.equal(q.musicVoices.at(-1).disconnected,true);
 fire(q);assert.equal(q.musicVoices.length,4);
 q.mute(false);assert.equal(q.musicVoices.length,5,'explicit unmute restores ambiance without reloading');
 q.hide(true);assert.equal(q.musicVoices.at(-1).disconnected,true);
 q.hide(false);await tick();assert.equal(q.musicVoices.length,5,'tab return alone cannot autoplay');
 q.open('resume');await tick();assert.equal(q.musicVoices.length,6);
 assert.equal(q.musicVoices.at(-1).buffer.id,2,'fresh context after hidden tab');
 q.blur();assert.equal(q.musicVoices.at(-1).disconnected,true);
 const padded=await start({musicDuration:10.8});
 nearly(padded.musicVoices[0].offset,.096+1105/24000);
 nearly(padded.musicVoices[0].loopEnd-padded.musicVoices[0].loopStart,10.56);
 const late=await start({musicDecodePending:true});
 late.key('keydown','KeyP');late.decodes.find(x=>x.name==='music').finish();
 assert.equal(late.musicVoices.length,0,'completed decode cannot play in pause');
 late.open('resume');assert.equal(late.musicVoices.length,1);
 const stale=await start({musicDecodePending:true});stale.hide(true);stale.hide(false);stale.open('resume');await tick();
 stale.decodes.find(x=>x.name==='music'&&x.id===1).finish();assert.equal(stale.musicVoices.length,0);
 stale.decodes.find(x=>x.name==='music'&&x.id===2).finish();assert.equal(stale.musicVoices[0].buffer.id,2);
 const blocked=await start({musicFetch:async()=>{throw Error('offline');}});
 fire(blocked);assert.equal(blocked.musicVoices.length,0);assert.equal(blocked.inspect().practiceShots,1);
 const invalid=await start({musicDuration:2});fire(invalid);
 assert.equal(invalid.musicVoices.length,0,'unexpected MP3 duration fails silent');assert.equal(invalid.inspect().practiceShots,1);
 console.log('PASS one quiet arena-only loop, protected wrap, shot ducking and V32 echo compatibility, lifecycle, native isolation and stale/failed decode.');
})().catch(e=>{console.error(e);process.exitCode=1;});
