'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict'),path=require('node:path'),crypto=require('node:crypto');
const {setup,tick}=require('./ballistic.test.cjs');
const dist=['../dist','..'].map(p=>path.join(__dirname,p)).find(p=>fs.existsSync(path.join(p,'fighter-winged.png')));
const png=fs.readFileSync(path.join(dist,'fighter-winged.png'));
assert.ok(png.subarray(0,8).equals(Buffer.from([137,80,78,71,13,10,26,10])));
assert.equal(png.toString('ascii',12,16),'IHDR');
assert.deepEqual([png.readUInt32BE(16),png.readUInt32BE(20),png[24],png[25]],[480,320,8,6],'PNG is 480×320 with 8-bit RGBA');
assert.equal(crypto.createHash('sha256').update(png).digest('hex'),'57a9dbdf7b57d97382ae578c6d75508112147e81602f924e7404d24dba1cc275');
assert.match(fs.readFileSync(path.join(dist,'index.html'),'utf8'),/<image id="hangar-fighter-art" href="\.\/fighter-winged\.png\?v=23"/);
(async()=>{
 const q=setup({sprite:true});assert.equal(q.sprites.length,1);
 const [art]=q.sprites;assert.equal(art.src,'./fighter-winged.png?v=23');
 q.open('start');await tick();q.step(2);
 assert.equal(q.spriteFrames.length,0,'vector fallback while the PNG is loading');
 art.complete=true;q.step(1);
 assert.equal(q.spriteFrames.length,0,'vector fallback when image loading fails');
 art.naturalWidth=480;q.step(1);
 const north=q.spriteFrames.at(-1);
 assert.equal(north.asset,art);
 assert.deepEqual(north.bounds,[-28.5,-24,57,38]);
 assert.equal(north.rotation,0,'north-facing artwork at native orientation');
 q.key('keydown','ArrowRight');q.key('keyup','ArrowRight');q.step(1);
 assert.equal(q.spriteFrames.at(-1).rotation,Math.PI/2,'sprite follows existing heading');
 const x=q.inspect().p.x,y=q.inspect().p.y;
 q.click('fire-button');
 const shot=q.inspect().shots[0];
 assert.deepEqual([shot.x,shot.y,shot.vx,shot.vy],[x+21,y,570,0],'existing muzzle spawn and motion');
 assert.equal(q.inspect().p.r,17,'unchanged physical radius');assert.equal(q.inspect().p.vx,-30,'unchanged Blaster recoil');
 q.step(1);assert.ok(q.spriteFrames.at(-1).translation[0]<q.inspect().p.x,'existing visual recoil');
 q.click('open-hangar');
 assert.equal(q.el.hangar.open,true);assert.equal(q.inspect().state,'pause');
 assert.equal(q.sprites.length,1,'single image instance for the Arena loop');
 console.log('PASS exact RGBA craft, loaded/failed/loading paths, aiming transform, muzzle geometry, recoil and Hangar art path.');
})().catch(e=>{console.error(e);process.exitCode=1;});
