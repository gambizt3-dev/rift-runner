'use strict';
const assert=require('node:assert/strict');
const {setup,tick}=require('./ballistic.test.cjs');
const fitKey='rift-runner.fighter-fit.v1';
const [blaster,ballistic]=['gun-blaster','gun-ballistic'];
const press=(q,code)=>{q.key('keydown',code);q.key('keyup',code);};
const plan=q=>JSON.parse(JSON.stringify(q.inspect().fighterFit));
const open=q=>q.click('open-hangar');
const close=q=>q.click('close-hangar');
(async()=>{
 const q=setup();
 assert.deepEqual(plan(q),{primary:'blaster',secondary:'ballistic'});
 assert.equal(q.rack.firstElementChild,q.el[blaster]);assert.equal(q.el[ballistic].hidden,false);
 open(q);assert.equal(q.el.hangar.open,true);assert.equal(q.inspect().state,'menu');
 q.fit('primary','ballistic');
 assert.deepEqual(plan(q),{primary:'ballistic',secondary:'blaster'});
 assert.equal(q.el['fit-secondary'].value,'blaster');
 assert.equal(q.rack.firstElementChild,q.el[ballistic]);assert.equal(q.inspect().shotSound,'ballistic');
 assert.deepEqual(JSON.parse(q.storage.get(fitKey)),{version:1,primary:'ballistic',secondary:'blaster'});
 close(q);assert.equal(q.el.hangar.open,false);assert.equal(q.inspect().state,'menu');
 q.open('start');await tick();assert.equal(q.inspect().state,'play');
 press(q,'Digit2');assert.equal(q.inspect().shotSound,'blaster');
 press(q,'Digit1');assert.equal(q.inspect().shotSound,'ballistic');
 q.pointer('pointerdown');q.step(20);
 assert.equal(q.inspect().practiceShots,2,'mounted Ballistic normal keeps hold cadence');
 const {x,y,vx,vy}=q.inspect().p;
 open(q);assert.equal(q.inspect().state,'pause');
 press(q,'Space');q.step(40);
 assert.equal(q.inspect().practiceShots,2);assert.deepEqual([q.inspect().p.x,q.inspect().p.y,q.inspect().p.vx,q.inspect().p.vy],[x,y,vx,vy]);
 q.fit('secondary',''); // No shield, no countermeasure, no secondary: still fly.
 assert.equal(q.el[blaster].hidden,true);assert.equal(q.el[ballistic].hidden,false);
 assert.deepEqual(plan(q),{primary:'ballistic',secondary:null});
 q.fit('secondary','ballistic');
 assert.equal(q.el['fit-secondary'].value,'');assert.match(q.el['fit-status'].textContent,/already on the primary/);
 close(q);assert.equal(q.inspect().state,'play');
 press(q,'Digit2');assert.equal(q.inspect().shotSound,'ballistic');
 q.click(blaster);assert.equal(q.inspect().shotSound,'ballistic','unmounted weapon cannot be selected');
 q.pointer('pointerdown');q.pointer('pointerup');assert.equal(q.inspect().practiceShots,3);
 press(q,'KeyP');assert.equal(q.inspect().state,'pause');open(q);close(q);
 assert.equal(q.inspect().state,'pause','opening Hangar on an existing pause cannot resume play');
 q.open('resume');
 open(q);q.hide(true);q.hide(false);close(q);
 assert.equal(q.inspect().state,'pause','backgrounding Hangar cannot silently resume flight');

 const reopened=setup({savedFit:q.storage.get(fitKey),saved:'blaster'});
 assert.deepEqual(plan(reopened),{primary:'ballistic',secondary:null});
 assert.equal(reopened.inspect().shotSound,'ballistic','unmounted legacy choice falls back to primary');
 assert.equal(reopened.el[blaster].hidden,true);
 open(reopened);assert.match(reopened.el['fit-status'].textContent,/A-Alkine primary · empty secondary/);close(reopened);
 reopened.open('start');await tick();assert.equal(reopened.inspect().state,'play','optional slots never block launch');
 reopened.click('fire-button');assert.equal(reopened.inspect().shots[0].weapon,'ballistic');
 const bad=setup({savedFit:'{"version":1,"primary":"none","secondary":"ballistic"}'});
 assert.deepEqual(plan(bad),{primary:'blaster',secondary:'ballistic'},'invalid primary recovers stock fit');
 const duplicates=setup({savedFit:'{"version":1,"primary":"ballistic","secondary":"ballistic"}'});
 assert.deepEqual(plan(duplicates),{primary:'ballistic',secondary:'blaster'},'invalid duplicate recovers unique mounts');
 const swap=setup();open(swap);swap.fit('secondary','blaster');
 assert.deepEqual(plan(swap),{primary:'ballistic',secondary:'blaster'},'equipping from either slot swaps occupied mounts');
 console.log('PASS Hangar stock options, no-duplicate swapping, saved/reloaded mounts, empty secondary flight, armed controls, and play/menu/pause/hidden lifecycle.');
})().catch(err=>{console.error(err);process.exitCode=1;});
