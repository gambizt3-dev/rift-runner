'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {setup,tick}=require('./ballistic.test.cjs');
const base=['../dist','..'].map(dir=>path.join(__dirname,dir)).find(dir=>fs.existsSync(path.join(dir,'index.html')));
const direction=q=>q.inspect().movePtr?.button?.dataset.move;
test('movement ring is itself a directional touch surface and highlights the active arrow',async()=>{
 const q=setup();q.choose('practice');await tick();
 const pad=q.el['move-pad'];
 q.pointer('pointerdown',1,'move-pad',143,460);
 assert.equal(direction(q),'e');
 assert.equal(pad.capture,1);assert.equal(pad.dataset.steering,'true');
 assert.equal(q.moveButtons.e.dataset.held,'true');
 q.step(4);assert.ok(q.inspect().p.vx>0);
 q.pointer('pointerup',1,'move-pad',143,460);
 assert.equal(q.inspect().movePtr,null);assert.equal(pad.capture,null);
 assert.equal(q.moveButtons.e.dataset.held,undefined);assert.equal(pad.dataset.steering,'false');
 q.pointer('pointerdown',8,'move-pad',98,455);
 assert.equal(direction(q),'e','inner space between buttons steers using a trim thruster');
 q.pointer('pointermove',8,'move-pad',80,460);assert.equal(direction(q),'e','an existing trim contact keeps trimming through the center');
 q.pointer('pointercancel',8,'move-pad');
 const css=fs.readFileSync(path.join(base,'style.css'),'utf8');
 assert.match(css,/\.dpad::before\{[^}]*inset:-2px -5px -6px;[^}]*touch-action:none/);
 assert.match(css,/\.dpad\[data-steering=true\]::before\{/);
 assert.match(css,/\.dpad button\[data-held=true\]/);
});
test('captured and uncaptured drags keep steering past the arrows, through center, and across directions',async()=>{
 const q=setup();q.choose('practice');await tick();
 const pad=q.el['move-pad'];pad.setPointerCapture=()=>{throw new Error('capture unavailable');};
 q.pointer('pointerdown',6,'move-pad',40,460,{target:q.moveButtons.w});
 assert.equal(direction(q),'w');
 q.pointer('pointermove',6,'move-pad',-25,460);assert.equal(direction(q),'w');
 q.outside('pointermove',{pointerId:6,clientX:80,clientY:350});assert.equal(direction(q),'n');
 assert.equal(q.moveButtons.w.dataset.held,undefined);
 q.pointer('pointermove',6,'move-pad',80,460);assert.equal(direction(q),'n');
 q.outside('pointermove',{pointerId:6,clientX:250,clientY:640});assert.equal(direction(q),'se');
 q.step(4);q.outside('pointerup',{pointerId:6});assert.equal(q.inspect().movePtr,null);assert.equal(q.inspect().movePulse,null);
});
test('movement cleanup follows its own pointer, leaving aim and FIRE independent',async()=>{
 const q=setup({saved:'ballistic'});q.choose('practice');await tick();
 q.pointer('pointerdown',1,'move-pad',80,407,{target:q.moveButtons.n});
 q.pointer('pointerdown',2,'aim-pad',280,200);
 q.pointer('pointerdown',3,'fire-button');
 assert.equal(q.inspect().aimPtr.id,2);assert.equal(q.inspect().ballisticHold.id,3);
 q.outside('pointermove',{pointerId:2,clientX:20,clientY:550});
 q.outside('pointerup',{pointerId:22});
 assert.equal(direction(q),'n');
 q.pointer('pointerup',2,'aim-pad');
 assert.equal(q.inspect().aimPtr,null);assert.equal(direction(q),'n');assert.equal(q.inspect().ballisticHold.id,3);
 q.pointer('lostpointercapture',1,'move-pad');
 assert.equal(q.inspect().movePtr,null);assert.equal(q.inspect().movePulse,null);assert.equal(q.inspect().ballisticHold.id,3);
 q.pointer('pointerup',3,'fire-button');
 q.pointer('pointerdown',4,'move-pad',80,514);assert.equal(direction(q),'s');
 q.outside('pointercancel',{pointerId:4});assert.equal(q.inspect().movePtr,null);assert.equal(q.inspect().movePulse,null);
 q.pointer('pointerdown',5,'move-pad',80,407);assert.equal(direction(q),'n');
 q.blur();assert.equal(q.inspect().movePtr,null);assert.equal(q.inspect().movePulse,null);
});
