'use strict';
const assert=require('node:assert/strict');
const {setup,tick}=require('./ballistic.test.cjs');
const heading=(q,x=240,y=370)=>{
 const {p,cones}=q.inspect();
 Object.assign(p,{x,y,vx:0,vy:0,aim:0});
 cones.splice(0);
};
const voices=q=>q.inspect().projectileVoices;
const live=q=>Array.from(voices(q).values());
const stopped=v=>v.osc.stops.at(-1)===undefined&&v.osc.disconnected;
(async()=>{
 const q=setup();q.open('start');await tick();heading(q);
 q.click('test-sound');assert.equal(voices(q).size,0,'shot preview is not a projectile');
 q.click('fire-button');
 const first=q.inspect().shots[0],hum=voices(q).get(first);
 assert.ok(hum);assert.equal(hum.osc.type,'triangle');assert.equal(hum.osc.frequency.sets[0][0],274);
 assert.ok(hum.osc.begins>=.02 && hum.osc.stops[0]>1);
 q.change('ballistic');q.click('fire-button');
 const zip=live(q).at(-1);assert.equal(zip.osc.type,'sine');assert.equal(zip.osc.frequency.sets[0][0],720);
 assert.ok(zip.osc.stops[0]-.022<=.59&&zip.osc.stops[0]-.022>.24,'faint ballistic tail lasts beyond the zip');
 assert.equal(voices(q).get(first),hum,'selecting a weapon does not change a shot already in flight');
 for(let i=0;i<4;i++){q.step(9);q.click('fire-button');}
 assert.equal(q.inspect().practiceShots,6);assert.equal(q.inspect().shots.length,6);
 assert.equal(voices(q).size,4);assert.equal(q.flightNotes.length,6);assert.ok(stopped(hum));assert.ok(stopped(zip));
 assert.equal(q.played.filter(v=>v.startsWith('ballistic:')).length,5,'separate voice cap does not touch firing audio');
 const naturallyEnds=live(q).at(-1);
 naturallyEnds.osc.onended();
 assert.equal(voices(q).size,3);assert.equal(naturallyEnds.osc.disconnected,true);assert.equal(naturallyEnds.osc.stops.length,1);
 q.step(75);assert.ok(q.inspect().shots.length>0,'later shots cross the former edge before reaching the new wall');
 q.step(12);assert.equal(q.inspect().shots.length,0);assert.equal(voices(q).size,0,'arena exit releases flight sound');
 const hit=setup();hit.open('start');await tick();
 const cone=hit.inspect().cones[0];heading(hit);Object.assign(cone,{x:330,y:370,vx:0,vy:0});hit.inspect().cones.push(cone);
 hit.click('fire-button');const hitsound=live(hit)[0];hit.step(14);
 assert.equal(hit.inspect().practiceHits,1);assert.ok(hitsound.releasing);
 const release=hitsound.level.gain.ramps.at(-1);
 assert.equal(release[0],0);assert.equal(release[1],hitsound.osc.stops.at(-1));
 hit.step(2);assert.ok(hitsound.osc.disconnected);assert.equal(voices(hit).size,0);
 const lifecycle=setup();lifecycle.open('start');await tick();heading(lifecycle);
 lifecycle.click('fire-button');const beforeMute=live(lifecycle)[0];
 lifecycle.mute();assert.equal(voices(lifecycle).size,0);assert.ok(stopped(beforeMute));
 lifecycle.step(14);lifecycle.click('fire-button');assert.equal(voices(lifecycle).size,0);assert.equal(lifecycle.inspect().practiceShots,2);
 lifecycle.mute(false);lifecycle.step(2);assert.equal(voices(lifecycle).size,0,'unmute never starts a past flight');
 lifecycle.step(14);lifecycle.click('fire-button');const beforePause=live(lifecycle)[0];
 lifecycle.key('keydown','KeyP');assert.ok(stopped(beforePause));assert.equal(voices(lifecycle).size,0);
 lifecycle.open('resume');lifecycle.step(2);assert.equal(voices(lifecycle).size,0,'resume never replays');
 lifecycle.step(14);lifecycle.click('fire-button');const beforeReset=live(lifecycle)[0];lifecycle.reset();
 assert.ok(stopped(beforeReset));assert.equal(lifecycle.inspect().practiceShots,0);assert.equal(voices(lifecycle).size,0);
 lifecycle.click('fire-button');const beforePreview=live(lifecycle)[0];
 lifecycle.click('test-phone-audio');assert.ok(stopped(beforePreview));assert.equal(voices(lifecycle).size,0);
 lifecycle.step(14);lifecycle.click('fire-button');assert.equal(voices(lifecycle).size,0,'no simultaneous native preview and flight audio');
 lifecycle.native[0].onended();lifecycle.step(14);lifecycle.click('fire-button');const beforeHide=live(lifecycle)[0];
 lifecycle.hide(true);assert.ok(stopped(beforeHide));assert.equal(voices(lifecycle).size,0);
 lifecycle.hide(false);lifecycle.open('resume');lifecycle.step(2);assert.equal(voices(lifecycle).size,0);
 const pending=setup({resumePending:true});pending.open('start');pending.click('fire-button');assert.equal(pending.inspect().practiceShots,1);
 assert.equal(pending.flightNotes.length,0,'no graph activation from a projectile');
 pending.hide(true);pending.resumes.shift()();await tick();assert.equal(pending.flightNotes.length,0,'late resolve while hidden cannot play old shot');
 pending.hide(false);pending.open('resume');pending.resumes.shift()();await tick();
 assert.equal(pending.flightNotes.length,0,'fresh resume cannot play old shot');
 pending.step(14);pending.click('fire-button');assert.equal(pending.flightNotes.length,1);assert.equal(pending.inspect().practiceShots,2);
 console.log('PASS Blaster hum and Ballistic zip use separate bounded flight voices, real shot count unchanged, hit/exit/cap/mute/reset/pause/native test/hide and stale resume stop or never revive sound.');
})().catch(e=>{console.error(e);process.exitCode=1;});
