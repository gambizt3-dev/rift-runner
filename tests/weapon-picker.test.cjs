'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const {setup}=require('./ballistic.test.cjs');
const htmlFile=['../dist/index.html','../index.html'].map(p=>path.join(__dirname,p)).find(p=>fs.existsSync(p));
const fitKey='rift-runner.fighter-fit.v1';
const slot=(q,id)=>q.click('fit-'+id+'-picture');
const pick=(q,id)=>q.click('fit-pick-'+id);
const readFit=q=>[q.inspect().fighterFit.primary,q.inspect().fighterFit.secondary];
const text=(q,id)=>q.el[id].textContent;
test('Weapon Selection uses pictures, fit stats and current selection; Back and Escape restore focus',()=>{
 const html=fs.readFileSync(htmlFile,'utf8');
 assert.match(html,/>Weapon Selection<\/h4>/);
 for(const asset of ['sterling-module.webp?v=58','alkine-module.webp?v=58','ak77-module.webp?v=58'])assert.ok(html.includes('./'+asset));
 const q=setup();
 q.click('open-hangar');
 assert.equal(q.el['fit-primary'].hidden,true);assert.equal(q.el['fit-secondary'].hidden,true);
 assert.equal(q.el['fit-primary-picture'].hidden,false);
 assert.equal(q.el['fit-primary-image'].getAttribute('src'),'./sterling-module.webp?v=58');
 assert.match(q.el['fit-primary-picture'].attrs['aria-label'],/primary weapon.*Sterling C\.32 Laser/);
 slot(q,'primary');
 assert.equal(q.el['fighter-fit-grid'].hidden,true);
 assert.equal(q.el['fit-weapon-picker'].hidden,false);
 assert.equal(text(q,'fit-picker-slot'),'Primary weapon');
 assert.equal(q.focused,q.el['fit-pick-blaster']);
 assert.equal(q.el['fit-primary-picture'].attrs['aria-expanded'],'true');
 assert.equal(q.el['fit-pick-blaster'].attrs['aria-pressed'],'true');
 assert.equal(q.el['fit-pick-empty'].hidden,true);
 assert.equal(text(q,'fit-pick-blaster-summary'),'3 dmg / shot · 6 in Burst');
 assert.equal(text(q,'fit-pick-ak77-summary'),'2 dmg / shot · 12-shot burst only');
 q.click('fit-picker-done');assert.equal(q.focused,q.el['fit-primary-picture']);
 assert.equal(q.el['fit-weapon-picker'].hidden,true);assert.equal(q.el['fighter-fit-grid'].hidden,false);
 slot(q,'secondary');assert.equal(text(q,'fit-picker-slot'),'Secondary weapon');assert.equal(q.el['fit-pick-empty'].hidden,false);
 assert.equal(q.focused,q.el['fit-pick-ballistic']);
 let prevented=false,stopped=false;
 q.el['fit-weapon-picker'].handlers.keydown({key:'Escape',preventDefault(){prevented=true;},stopPropagation(){stopped=true;}});
 assert.equal(prevented&&stopped,true);assert.equal(q.el.hangar.open,true);
 assert.equal(q.focused,q.el['fit-secondary-picture']);assert.equal(q.el['fit-weapon-picker'].hidden,true);
 assert.deepEqual(readFit(q),['blaster','ballistic']);
});
test('illustrated selection preserves save, swaps and empty secondary; inspection is always read-only',()=>{
 const q=setup();q.click('open-hangar');
 slot(q,'primary');assert.equal(text(q,'fit-pick-ballistic-status'),'Swap mounts');pick(q,'ballistic');
 assert.deepEqual(readFit(q),['ballistic','blaster']);assert.equal(q.focused,q.el['fit-primary-picture']);
 assert.equal(q.el['fit-primary-image'].getAttribute('src'),'./alkine-module.webp?v=58');
 assert.equal(q.el['fit-secondary-image'].getAttribute('src'),'./sterling-module.webp?v=58');
 slot(q,'secondary');pick(q,'empty');
 assert.deepEqual(readFit(q),['ballistic',null]);assert.equal(q.el['fit-secondary-image'].getAttribute('src'),null);
 assert.equal(q.el['fit-secondary-empty'].hidden,false);
 slot(q,'secondary');assert.equal(text(q,'fit-pick-ballistic-status'),'On primary');pick(q,'ballistic');
 assert.deepEqual(readFit(q),['ballistic',null]);assert.equal(q.el['fit-weapon-picker'].hidden,false);
 assert.match(text(q,'fit-status'),/already on the primary mount/);
 pick(q,'ak77');assert.deepEqual(readFit(q),['ballistic','ak77']);
 assert.equal(q.el['fit-secondary-image'].getAttribute('src'),'./ak77-module.webp?v=58');
 slot(q,'primary');q.click('inspect-vandul');
 assert.equal(q.el['fit-weapon-picker'].hidden,true);
 slot(q,'primary');pick(q,'blaster');assert.equal(q.el['fit-weapon-picker'].hidden,true);
 assert.deepEqual(readFit(q),['ballistic','ak77']);
 q.click('close-hangar');q.click('open-hangar');
 assert.equal(q.el['fit-weapon-picker'].hidden,true);
 const saved=setup({savedFit:q.storage.get(fitKey)});
 assert.deepEqual(readFit(saved),['ballistic','ak77']);
 assert.equal(saved.el['fit-secondary-image'].getAttribute('src'),'./ak77-module.webp?v=58');
});
